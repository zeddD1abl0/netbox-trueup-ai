package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

const schema = `{
  "openapi": "3.0.3",
  "info": {"version": "4.7.2-Docker-5.1.1 (4.7)"},
  "paths": {},
  "components": {"schemas": {
    "Thing": {"type": "object", "properties": {
      "role": {"type": "object", "properties": {"value": {"enum": ["parent", "child \"quoted\"", "", null]}}, "nullable": true},
      "size": {"type": "object", "properties": {"value": {"enum": ["s", "m"]}}}
    }}
  }}
}`

func TestGenerate(t *testing.T) {
	t.Parallel()
	src, err := generate([]byte(schema), "testdata/openapi.json", "dcim")
	if err != nil {
		t.Fatal(err)
	}
	want := `// Code generated by netbox-choices from testdata/openapi.json; DO NOT EDIT.

package dcim

// choiceValues holds the values of each choice field in NetBox's OpenAPI
// schema, by response component and field, in NetBox's order and without the
// blank choice, as NetBox 4.7.2-Docker-5.1.1 (4.7) gives them.
var choiceValues = map[string][]string{
	"Thing.role": {
		"parent",
		"child \"quoted\"",
	},
	"Thing.size": {
		"s",
		"m",
	},
}
`
	if string(src) != want {
		t.Errorf("generate wrote:\n%s\nwant:\n%s", src, want)
	}
}

func TestGenerateRefuses(t *testing.T) {
	t.Parallel()
	for name, data := range map[string]string{
		"a version that ends the comment": strings.Replace(schema, `4.7.2-Docker-5.1.1 (4.7)`, `4.7.2\nvar x = 1`, 1),
		"no version":                      strings.Replace(schema, `"4.7.2-Docker-5.1.1 (4.7)"`, `""`, 1),
		"a choice that isn't a string":    strings.Replace(schema, `"s", "m"`, `"s", 2`, 1),
		"not OpenAPI 3.0":                 strings.Replace(schema, `3.0.3`, `3.1.0`, 1),
	} {
		if src, err := generate([]byte(data), "x.json", "dcim"); err == nil {
			t.Errorf("%s: generate wrote\n%s", name, src)
		}
	}
}

func TestRun(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	in, out := filepath.Join(dir, "openapi.json"), filepath.Join(dir, "choices_gen.go")
	if err := os.WriteFile(in, []byte(schema), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := run(in, "dcim", out); err != nil {
		t.Fatal(err)
	}
	if src, err := os.ReadFile(out); err != nil || !strings.Contains(string(src), `"Thing.size"`) { //nolint:gosec // G703: a file in the test's own directory.
		t.Errorf("run wrote %q, %v", src, err)
	}
	for _, args := range [][3]string{{"", "dcim", out}, {in, "", out}, {in, "not a name", out}, {in, "dcim", ""}, {filepath.Join(dir, "missing.json"), "dcim", out}} {
		if err := run(args[0], args[1], args[2]); err == nil {
			t.Errorf("run(%q) gave no error", args)
		}
	}
}
