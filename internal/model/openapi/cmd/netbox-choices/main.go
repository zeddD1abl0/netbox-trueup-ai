// Command netbox-choices generates a spec package's choice values from a
// snapshot of NetBox's OpenAPI schema: a map from component and field, such
// as DeviceType.airflow, to the field's values. `make generate` runs it for
// each spec package, and `make generate-check` checks that what it writes
// matches the committed file. Choice values are generated so that a spec
// can't miss a value NetBox adds; the contract tests check specs against the
// same schema.
//
//	netbox-choices -schema internal/model/dcim/testdata/openapi.json -package dcim -out internal/model/dcim/choices_gen.go
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"go/token"
	"os"
	"regexp"
	"strconv"

	"github.com/zeddD1abl0/netbox-trueup-ai/internal/model/openapi"
)

func main() {
	schema := flag.String("schema", "", "the schema snapshot to read")
	pkg := flag.String("package", "", "the Go package to generate")
	out := flag.String("out", "", "the Go file to write")
	flag.Parse()
	if err := run(*schema, *pkg, *out); err != nil {
		fmt.Fprintln(os.Stderr, "netbox-choices:", err)
		os.Exit(1)
	}
}

func run(schema, pkg, out string) error {
	if schema == "" || out == "" || !token.IsIdentifier(pkg) {
		return fmt.Errorf("usage: netbox-choices -schema FILE -package NAME -out FILE")
	}
	data, err := os.ReadFile(schema) //nolint:gosec // G304: a developer names the snapshot to read.
	if err != nil {
		return err
	}
	src, err := generate(data, schema, pkg)
	if err != nil {
		return err
	}
	return os.WriteFile(out, src, 0o644) //nolint:gosec // G306: generated source, committed and world-readable like the rest.
}

// version matches the schema's info.version, such as "4.7.2-Docker-5.1.1 (4.7)".
var version = regexp.MustCompile(`^[0-9][0-9A-Za-z.+() -]*$`)

// generate writes the Go source of package pkg's choice values, from the
// schema snapshot data that the file schema holds.
func generate(data []byte, schema, pkg string) ([]byte, error) {
	d, err := openapi.Load(data)
	if err != nil {
		return nil, err
	}
	// The version goes into a comment, so it mustn't end the line.
	if !version.MatchString(d.Info.Version) {
		return nil, fmt.Errorf("the schema's version %q isn't a NetBox version", d.Info.Version)
	}
	sets, err := d.Choices()
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by netbox-choices from %s; DO NOT EDIT.\n\n", schema)
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	fmt.Fprintf(&b, "// choiceValues holds the values of each choice field in NetBox's OpenAPI\n")
	fmt.Fprintf(&b, "// schema, by response component and field, in NetBox's order and without the\n")
	fmt.Fprintf(&b, "// blank choice, as NetBox %s gives them.\n", d.Info.Version)
	fmt.Fprintf(&b, "var choiceValues = map[string][]string{\n")
	for _, s := range sets {
		fmt.Fprintf(&b, "\t%s: {\n", strconv.Quote(s.Key))
		for _, v := range s.Values {
			fmt.Fprintf(&b, "\t\t%s,\n", strconv.Quote(v))
		}
		fmt.Fprintf(&b, "\t},\n")
	}
	fmt.Fprintf(&b, "}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format the generated code: %w", err)
	}
	return src, nil
}
